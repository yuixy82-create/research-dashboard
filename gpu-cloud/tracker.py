def daily_series(cache, fn):
    """일별 스냅샷에서 (날짜, 값) 시계열을 뽑는다."""
    out = []
    for day in sorted(cache.get("daily", {})):
        try:
            v = fn(cache["daily"][day])
            if v is not None:
                out.append((day, round(float(v), 4)))
        except Exception:
            continue
    return out


