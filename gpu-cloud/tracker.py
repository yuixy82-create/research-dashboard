def change_over(pts, days=30):
    """(절대변화, 퍼센트변화) — 데이터가 모자라면 (None, None)."""
    if len(pts) < 2:
        return None, None
    last_d, last_v = pts[-1]
    tgt = (date.fromisoformat(last_d) - timedelta(days=days)).isoformat()
    prior = [p for p in pts if p[0] <= tgt]
    base = prior[-1] if prior else pts[0]
    if not base[1]:
        return None, None
    return round(last_v - base[1], 4), round((last_v / base[1] - 1) * 100, 1)


