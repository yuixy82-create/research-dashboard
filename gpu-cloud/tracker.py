    day = today_kst()
    since = (datetime.now(KST) - timedelta(days=400)).strftime("%Y-%m-%d")
    print("== %s 수집 시작 ==" % day)

    snap = {}
    print("[1/5] 업체 정가 바스켓 (업체 공식 가격 페이지 직접 수집)")
    b = collect_basket()
