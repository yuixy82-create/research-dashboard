def svg_chart(series, w=680, h=270, yfmt=None, zero_base=False):
    """series: [{label,color,points:[(날짜,값)],dash,width,markers}]"""
    yfmt = yfmt or (lambda v: f"${v:,.2f}")
    series = [s for s in series if s.get("points")]
    if not series:
        return ('<div style="color:%s;font-size:12px;padding:26px 4px">'
                '데이터 수집 대기 중 — 자동 수집이 쌓이면 그려집니다</div>' % T["faint"])
    ml, mr, mt, mb = 54, 192, 12, 26
    pw, ph = w - ml - mr, h - mt - mb
    xs = [d2o(p[0]) for s in series for p in s["points"]]
    ys = [p[1] for s in series for p in s["points"]]
    x0, x1 = min(xs), max(xs)
    if x0 == x1:
        x0, x1 = x0 - 1, x1 + 1
    lo, hi = min(ys), max(ys)
    pad = (hi - lo) * 0.15 or abs(hi) * 0.1 or 1
    y0, y1 = lo - pad, hi + pad
    if zero_base or (lo >= 0 and y0 < 0.25 * (hi - lo)):
        y0 = 0
    X = lambda o: ml + (o - x0) / (x1 - x0) * pw
    Y = lambda v: mt + (1 - (v - y0) / (y1 - y0)) * ph

    o = ['<svg viewBox="0 0 %d %d" xmlns="http://www.w3.org/2000/svg" '
         'style="width:100%%;height:auto;font-family:inherit">' % (w, h)]
    for i in range(4):
        v = y0 + (y1 - y0) * i / 3
        yy = Y(v)
        o.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="%s" stroke-width="%s"/>'
                 % (ml, yy, w - mr, yy, T["hair"], 1 if i == 0 else 0.6))
        o.append('<text x="%d" y="%.1f" text-anchor="end" font-size="9.5" fill="%s">%s</text>'
                 % (ml - 6, yy + 3, T["muted"], yfmt(v)))
    span = x1 - x0
    xf = "%y.%m" if span > 70 else "%m.%d"
    n = min(5, max(3, span // 30 + 2))
    for i in range(int(n)):
        ov = x0 + span * i / (n - 1)
        o.append('<text x="%.1f" y="%d" text-anchor="middle" font-size="9.5" fill="%s">%s</text>'
                 % (X(ov), h - 8, T["muted"], date.fromordinal(int(ov)).strftime(xf)))

    ends = []
    for s in series:
        pts = sorted(s["points"], key=lambda p: p[0])
        co = [(X(d2o(p[0])), Y(p[1])) for p in pts]
        dash = ' stroke-dasharray="5,4"' if s.get("dash") else ""
        if len(co) > 1:
            o.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="%s"%s '
                     'stroke-linejoin="round"/>'
                     % (" ".join("%.1f,%.1f" % c for c in co), s["color"],
                        s.get("width", 2.1), dash))
        if len(co) <= 8 or s.get("markers"):
            for cx, cy in co:
                o.append('<circle cx="%.1f" cy="%.1f" r="3" fill="%s" stroke="#fff" '
                         'stroke-width="1.2"/>' % (cx, cy, s["color"]))
        o.append('<circle cx="%.1f" cy="%.1f" r="2.6" fill="%s" stroke="#fff" '
                 'stroke-width="1"/>' % (co[-1][0], co[-1][1], s["color"]))
        dtxt = ""
        if len(pts) > 1:
            prev, last = pts[-2][1], pts[-1][1]
            days = d2o(pts[-1][0]) - d2o(pts[-2][0])
            suffix = "전일比" if days <= 3 else (
                date.fromisoformat(pts[-2][0]).strftime("%m.%d") + "比")
            f = yfmt(last)
            if "bp" in f:
                dtxt = "%+.0fbp" % (last - prev)
            elif "%" in f:
                dtxt = "%+.0fbp" % ((last - prev) * 100)
            elif "$" in f and prev:
                dtxt = "%+.1f%%" % ((last / prev - 1) * 100)
            elif "M" in f:
                dtxt = "%+.1fM" % (last - prev)
            else:
                dtxt = "%+.2f" % (last - prev)
            dtxt += " " + suffix
        ends.append([co[-1][0] + 7, co[-1][1] + 3, s["color"],
                     "%s %s (%s)" % (s["label"], yfmt(pts[-1][1]),
                                     date.fromisoformat(pts[-1][0]).strftime("%y.%m.%d")),
                     dtxt])
    ends.sort(key=lambda e: e[1])
    gap = 24 if any(e[4] for e in ends) else 13
    for i in range(1, len(ends)):
        if ends[i][1] - ends[i - 1][1] < gap:
            ends[i][1] = ends[i - 1][1] + gap
    for ex, ey, col, txt, dtxt in ends:
        yy = min(ey, h - 24)
        o.append('<text x="%.1f" y="%.1f" font-size="10" font-weight="700" fill="%s">%s</text>'
                 % (ex, yy, col, htmlmod.escape(txt)))
        if dtxt:
            o.append('<text x="%.1f" y="%.1f" font-size="9" fill="%s" opacity="0.75">'
                     '%s</text>' % (ex, yy + 11, col, htmlmod.escape(dtxt)))
    o.append("</svg>")
    return "".join(o)


