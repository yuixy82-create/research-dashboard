def http_get(url, retries=2, timeout=25, headers=None):
    """GET → 본문 텍스트. 실패해도 예외를 던지지 않고 None (부분 실패 허용)."""
    h = {"User-Agent": UA, "Accept-Language": "en-US,en;q=0.9"}
    if headers:
        h.update(headers)
    for i in range(retries):
        try:
            req = urllib.request.Request(url, headers=h)
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read().decode("utf-8", errors="replace")
        except Exception as e:
            print(f"  [warn] GET {url[:70]} 시도 {i+1}/{retries}: {e}")
            time.sleep(2 * (i + 1))
    return None


def http_post_json(url, payload, retries=2, timeout=25):
    body = json.dumps(payload).encode()
    for i in range(retries):
        try:
            req = urllib.request.Request(
                url, data=body,
                headers={"User-Agent": UA, "Content-Type": "application/json"},
                method="POST")
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return json.loads(r.read().decode())
        except Exception as e:
            print(f"  [warn] POST {url[:60]} 시도 {i+1}/{retries}: {e}")
            time.sleep(2 * (i + 1))
    return None


def median(xs):
    xs = sorted(x for x in xs if x is not None)
    if not xs:
        return None
    n = len(xs)
    m = n // 2
    return round(xs[m] if n % 2 else (xs[m - 1] + xs[m]) / 2, 4)


def load_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def save_json(path, obj):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")


